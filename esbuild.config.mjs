import esbuildSvelte from "esbuild-svelte";
import { sveltePreprocess } from "svelte-preprocess";
import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import { readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * Obsidian only reloads styles.css with the plugin. Svelte's injected styles
 * stay in the page under the same id across reloads, so a rebuilt component
 * kept its old styles until Obsidian restarted. Instead the component CSS is
 * emitted by esbuild (main.css) and joined with src/styles.css into styles.css.
 */
const stylesCss = {
	name: "styles-css",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0) return;
			const components = existsSync("main.css") ? readFileSync("main.css", "utf8") : "";
			rmSync("main.css", { force: true });
			const header = "/* Generated from src/styles.css and the Svelte components. Edit those. */\n";
			writeFileSync("styles.css", `${header}${readFileSync("src/styles.css", "utf8")}\n${components}`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [
		esbuildSvelte({
			compilerOptions: { css: "external" },
			preprocess: sveltePreprocess(),
		}),
		stylesCss,
	],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
